# -*- coding: utf-8 -*-
"""Record that every agent on the 563-scene split reproduces its committed per-scene CSV when
scored again from the code in this repository.

Run in the NAVSIM workspace after the re-runs: each agent is scored with the exact hydra
overrides of its canonical run (``code/hydra/overrides.yaml``), only ``experiment_name`` changed
to ``<tag>/<agent>``; ``privileged_brake_mini`` additionally with ``<tag>/privileged_brake_*``
runs under other workers. This script fingerprints every run (ladder_io.fingerprint: token,
valid and all sub-scores, rows sorted by token) and writes

    results/rerun_check.json   the fingerprints, the worker of each run
    results/rerun_check.md     the same as a table

``tests/test_rerun_check.py`` then checks, with no workspace, that each committed CSV still has
the fingerprint the re-runs produced, and that the markdown is regenerated byte for byte.

    python analysis/rerun_check.py --exp D:/navsim_workspace/exp --tag rerun_20260924
    python analysis/rerun_check.py --render      # rewrite the .md from the committed .json
"""
import argparse
import csv
import glob
import io
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ladder_io import PER_SCENE, REPO, csv_path, fingerprint, pinned_runs  # noqa: E402
from make_summary import AGENTS  # noqa: E402

JSON_OUT = os.path.join(REPO, 'results', 'rerun_check.json')
MD_OUT = os.path.join(REPO, 'results', 'rerun_check.md')
SUPERSEDED = 'privileged_brake_mini_superseded'
# extra re-runs of the one agent whose August runs disagreed, under other workers
EXTRA = {'privileged_brake_mini': ['privileged_brake_seq_a', 'privileged_brake_seq_b',
                                   'privileged_brake_threads', 'privileged_brake_procs']}
# what was checked by hand about an agent that is not bit-identical (kept in the json, shown in the md)
NOTES = {'speed_mlp_mini': 'The two re-runs agree with each other bit for bit and differ from the September 2 run '
                           'in one scene (`494fade53c845a1b`, ego progress, 8.3e-11). The agent file, its checkpoint '
                           'and every library in the environment predate that run and are unchanged, so this is a '
                           'float-level difference in the network\'s CPU inference between the two sessions.'}


def overrides(run_dir):
    """hydra overrides of one run, from its code/hydra/overrides.yaml (a plain '- k=v' list)."""
    path = os.path.join(run_dir, 'code', 'hydra', 'overrides.yaml')
    out = {}
    for line in io.open(path, encoding='utf-8').read().splitlines():
        line = line.strip()
        if line.startswith('- ') and '=' in line:
            k, v = line[2:].split('=', 1)
            out[k.strip()] = v.strip()
    return out


def worker_label(ov):
    w = ov.get('worker', 'sequential')
    if w == 'sequential':
        return 'sequential'
    kind = 'process pool' if ov.get('worker.use_process_pool', 'false').lower() == 'true' else 'thread pool'
    return '%s, %s workers' % (kind, ov.get('worker.max_workers', 'all'))


def compare(a_path, b_path):
    """(scenes with every column bit-identical, largest absolute difference in any sub-score)."""
    def rows(p):
        with io.open(p, encoding='utf-8') as f:
            return {r['token']: r for r in csv.DictReader(f) if r.get('token') and r['token'] != 'average'}
    a, b = rows(a_path), rows(b_path)
    cols = [c for c in next(iter(a.values())) if c not in ('', 'token', 'valid')]
    same, worst = 0, 0.0
    for t in a:
        if t not in b or a[t]['valid'] != b[t]['valid']:
            worst = float('inf')
            continue
        d = max(abs(float(a[t][c]) - float(b[t][c])) for c in cols)
        same += d == 0.0
        worst = max(worst, d)
    return same, worst


def collect(exp, tag):
    ws = os.path.dirname(os.path.abspath(exp))
    rel = lambda p: os.path.relpath(p, ws).replace(os.sep, '/')  # noqa: E731
    pins = pinned_runs()
    agents = {}
    for _name, sub in AGENTS:
        canonical = csv_path(exp, sub)
        committed = os.path.join(PER_SCENE, sub + '.csv')
        sha, n = fingerprint(committed)
        rec = {'canonical_run': pins.get(sub, rel(canonical)), 'committed_sha256': sha, 'scenes': n,
               'canonical_sha256': fingerprint(canonical)[0], 'reruns': []}
        for d in sorted([sub] + EXTRA.get(sub, [])):
            for f in sorted(glob.glob(os.path.join(exp, tag, d, '*', '*.csv'))):
                run_dir = os.path.dirname(f)
                s, m = fingerprint(f)
                same, worst = compare(committed, f)
                rec['reruns'].append({'run': rel(f), 'worker': worker_label(overrides(run_dir)),
                                      'sha256': s, 'scenes': m, 'identical_scenes': same, 'max_abs_diff': worst})
        agents[sub] = rec
    sup = os.path.join(PER_SCENE, SUPERSEDED + '.csv')
    s, m = fingerprint(sup)
    same, worst = compare(os.path.join(PER_SCENE, 'privileged_brake_mini.csv'), sup)
    return {'tag': tag, 'agents': agents, 'notes': NOTES,
            'superseded': {'file': 'results/per_scene/%s.csv' % SUPERSEDED, 'source': pins.get(SUPERSEDED),
                           'sha256': s, 'scenes': m, 'identical_scenes_vs_canonical': same,
                           'max_abs_diff_vs_canonical': worst}}


def render_md(data):
    L = ['# Re-run check: every agent on the 563-scene split, scored again from the current code\n']
    L.append('Each agent was scored again with the exact hydra overrides of its canonical run (only '
             '`experiment_name` changed, to `%s/<agent>`) and the result fingerprinted: token, `valid` and '
             'all six sub-scores plus PDMS for every scene, sorted by token. Row order is not part of the '
             'fingerprint -- NAVSIM writes the scenes in a different order on each run, which moves nothing '
             'but the last bit of the printed mean. Generated by `analysis/rerun_check.py`; '
             '`tests/test_rerun_check.py` checks the committed CSVs against it on every push.\n' % data['tag'])
    L.append('| agent | canonical run | re-runs (worker) | scenes identical to the committed CSV |')
    L.append('|---|---|---|---|')
    exact, worst = 0, 0.0
    for sub, rec in data['agents'].items():
        workers = '; '.join(r['worker'] for r in rec['reruns'])
        same = '; '.join('%d of %d' % (r['identical_scenes'], rec['scenes'])
                         + ('' if r['identical_scenes'] == rec['scenes'] else ', the rest within %.1e' % r['max_abs_diff'])
                         for r in rec['reruns'])
        exact += all(r['sha256'] == rec['committed_sha256'] for r in rec['reruns'])
        worst = max([worst] + [r['max_abs_diff'] for r in rec['reruns']])
        L.append('| `%s` | `%s` | %s | %s |' % (sub, rec['canonical_run'].split('/', 2)[-1].rsplit('/', 1)[0],
                                               workers, same))
    L.append('\n%d of %d agents reproduce their committed per-scene CSV bit for bit in every re-run; the largest '
             'difference anywhere is %.1e, in a sub-score that is reported to three decimals.\n'
             % (exact, len(data['agents']), worst))
    for sub, note in sorted(data.get('notes', {}).items()):
        L.append('`%s`: %s\n' % (sub, note))
    s = data['superseded']
    L.append('The superseded first run of `privileged_brake_mini` (`%s`, kept as `%s`) matches the '
             'canonical run in %d of %d scenes; why is in [brake_rerun_diff.md](brake_rerun_diff.md).\n'
             % (s['source'], s['file'].split('/')[-1], s['identical_scenes_vs_canonical'], s['scenes']))
    return '\n'.join(L)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--exp', help='the NAVSIM workspace exp/ folder holding the re-runs')
    ap.add_argument('--tag', default='rerun_20260924', help='experiment_name prefix of the re-runs')
    ap.add_argument('--render', action='store_true', help='only rewrite the .md from the committed .json')
    a = ap.parse_args(argv)
    if a.render:
        data = json.load(io.open(JSON_OUT, encoding='utf-8'))
    else:
        if not a.exp:
            ap.error('--exp is required unless --render')
        data = collect(a.exp, a.tag)
        io.open(JSON_OUT, 'w', encoding='utf-8', newline='\n').write(json.dumps(data, indent=1) + '\n')
    io.open(MD_OUT, 'w', encoding='utf-8', newline='\n').write(render_md(data))
    print('wrote', MD_OUT)


if __name__ == '__main__':
    main()
